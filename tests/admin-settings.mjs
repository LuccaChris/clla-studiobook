import assert from "node:assert/strict";

const origin = process.env.TEST_ORIGIN;
assert(origin, "Configure TEST_ORIGIN para banco descartável.");
const base = new URL("/api/salons/", origin).href;
const headers = {"Content-Type":"application/json","X-StudioBook":"1"};
const A="studio-amaral", B="barbearia-lopes";
const keys = ["TEST_EMAIL_A","TEST_PASSWORD_A","TEST_EMAIL_B","TEST_PASSWORD_B"];
assert(keys.every(k=>process.env[k]), "Configure credenciais fictícias no ambiente.");
const [ea,pa,eb,pb]=keys.map(k=>process.env[k]);
const get = (p,c) => fetch(base+p,{headers:c?{Cookie:c}:{}});
const post = (p,body,c) => fetch(base+p,{method:"POST",headers:c?{...headers,Cookie:c}:headers,body:JSON.stringify(body)});
const admin = (slug,p) => slug+"/admin/"+p;
const login=async(slug,email,password)=> {
  const r=await post(slug+"/login",{email,password}); assert.equal(r.status,204);
  const c=r.headers.getSetCookie()[0]; assert.match(c,/^studiobook.admin=/); return c.split(";")[0];
};
const a=await login(A,ea,pa), b=await login(B,eb,pb);
assert.equal((await get(admin(A,"settings"))).status,401);
assert.equal((await get(admin(B,"settings"),a)).status,403);
for(const path of ["profile","services","hours","blocks","blocks/remove"])
  assert.equal((await post(admin(B,path),{},a)).status,403);
const settings=async(slug,c)=>{const r=await get(admin(slug,"settings"),c);assert.equal(r.status,200);return r.json()};
const status=async(path,payload,want)=>{const r=await post(admin(A,path),payload,a);assert.equal(r.status,want,await r.text())};
const beforeB=await settings(B,b);
const profile={name:"Studio Amaral QA",address:"Endereço fictício QA",description:"Perfil editado",directoryPhone:"+55 (11) 00000-0092",imageUrl:"https://example.com/test.webp"};
await status("profile",{...profile,directoryPhone:beforeB.directoryPhone},409);
await status("profile",profile,204);
const info=await get(A).then(r=>r.json());assert.equal(info.name,profile.name);assert.equal(info.imageUrl,profile.imageUrl);
assert.equal((await get("directory/lookup?phone=11000000092").then(r=>r.json())).slug,A);
const service={name:"Serviço QA 40",description:"Teste de pausa",priceInCents:4200,minutes:40,active:true};
await status("services",{...service,id:beforeB.services[0].id},404);
await status("services",service,204);
const id=(await settings(A,a)).services.find(x=>x.name===service.name).id;
const day=(i)=>new Intl.DateTimeFormat("sv-SE",{timeZone:"America/Sao_Paulo",year:"numeric",month:"2-digit",day:"2-digit"}).format(new Date(Date.now()+i*864e5));
const [one,two]=[day(12),day(13)];
const hours={opens:"08:00",closes:"18:00",breakStart:"12:00",breakEnd:"13:00",workdays:[1,2,3,4,5,6,7]};
await status("hours",{...hours,breakEnd:null},400);
await status("hours",hours,204);
const slots=(d)=>get(A+"/slots?"+new URLSearchParams({serviceId:id,day:d})).then(r=>r.json());
const times=await slots(one);
assert(times.includes("11:15")); assert(!times.includes("11:30")); assert(!times.includes("12:00")); assert(times.includes("13:00"));
const collision=await post(A+"/bookings",{serviceId:id,customer:"Cliente fictício QA",day:one,time:"11:30"});assert.equal(collision.status,409);
const confirm=await post(A+"/bookings",{serviceId:id,customer:"Cliente fictício QA",day:one,time:"11:15"});
assert.equal(confirm.status,200);
const {manageCode:code}=await confirm.json();
await status("blocks",{day:one,note:"Folga"},409);
await status("hours",{...hours,breakStart:"11:30"},409);
await status("blocks",{day:two,note:"Feriado"},204);
assert.deepEqual(await slots(two),[]);
const available=async()=>get(A+"/availability?"+new URLSearchParams({serviceId:id,start:one,end:two})).then(r=>r.json());
assert.deepEqual(await available(),[one]);
await status("blocks/remove",{day:two},204);assert((await slots(two)).length>0);
await status("services",{...service,id,minutes:50,active:false},204);
assert.deepEqual(await slots(two),[]);
assert(!(await get(A).then(r=>r.json())).services.some(s=>s.id===id));
const change=await post("customer-bookings/reschedule",{code,revision:0,day:two,time:"11:15"});
assert.equal(change.status,204);
assert.equal((await post("customer-bookings/details",{code}).then(r=>r.json())).minutes,40);
assert.deepEqual(await settings(B,b),beforeB);
console.log("Admin: isolamento, perfil, serviços, pausas, folgas e preservação de reservas verificados.");

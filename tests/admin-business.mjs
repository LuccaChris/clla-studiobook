async function request(path, method="GET", data, cookie, code=200) {
  const headers=cookie?{Cookie:cookie}:{};
  if(method==="POST") Object.assign(headers,{"Content-Type":"application/json","X-StudioBook":"1"});
  const r=await fetch(base+path,{method,headers,body:data===undefined?undefined:JSON.stringify(data)});
  assert.equal(r.status,code,method+" "+path+" "+(r.status!==code?await r.text():""));
  return r;
}
